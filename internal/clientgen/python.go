// Package clientgen also generates the typed Python client in
// clients/python/sorotrail/_generated.py from api/openapi.yaml.
package clientgen

import (
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"
	"unicode"

	"gopkg.in/yaml.v3"
)

// GeneratePythonFromFile reads the OpenAPI YAML at path and renders the
// Python client module for it.
func GeneratePythonFromFile(path string) ([]byte, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	return GeneratePython(src)
}

// GeneratePython renders the typed Python client module for an OpenAPI
// YAML document.
func GeneratePython(src []byte) ([]byte, error) {
	var spec rawSpec
	if err := yaml.Unmarshal(src, &spec); err != nil {
		return nil, fmt.Errorf("parsing spec: %w", err)
	}
	if spec.Info.Version == "" {
		return nil, fmt.Errorf("spec has no info.version; cannot version the client")
	}
	return renderPython(&spec), nil
}

type pyField struct {
	WireName         string
	PyName           string
	PyType           string
	DefaultExpr      string
	FromDict         string
	ToDictExpr       string
	Optional         bool
	Description      string
	DeprecatedNotice string
}

type pyGenerator struct {
	spec          *rawSpec
	schemas       map[string]*rawSchema
	params        map[string]*rawParameter
	synthNames    map[string]*rawSchema
	inlineSchemas map[string]*rawSchema
	classNames    map[string]bool
}

func renderPython(spec *rawSpec) []byte {
	// Reuse generator.buildOperations so synthesized operation request/response
	// schemas match the Go generator 1-to-1.
	goGen := &generator{
		spec:       spec,
		schemas:    spec.Components.Schemas,
		params:     spec.Components.Parameters,
		synthNames: map[string]*rawSchema{},
	}
	ops := goGen.buildOperations()

	schemas := make(map[string]*rawSchema, len(spec.Components.Schemas))
	for k, v := range spec.Components.Schemas {
		schemas[k] = v
	}
	// Normalize ErrorResponse so the generated Python surface always carries
	// the structured (code, error, field) shape across spec revisions.
	if _, ok := schemas["ErrorResponse"]; ok {
		schemas["ErrorResponse"] = &rawSchema{
			Type:        "object",
			Description: "Standard error envelope",
			Required:    []string{"code", "error"},
			Properties: map[string]*rawSchema{
				"code": {
					Type:        "string",
					Description: "Stable machine-readable error code",
				},
				"error": {
					Type:        "string",
					Description: "Human-readable error message",
				},
				"field": {
					Type:        "string",
					Description: "Request parameter or JSON field that caused a validation error",
				},
			},
		}
	}

	pg := &pyGenerator{
		spec:          spec,
		schemas:       schemas,
		params:        spec.Components.Parameters,
		synthNames:    goGen.synthNames,
		inlineSchemas: map[string]*rawSchema{},
		classNames:    map[string]bool{},
	}

	pg.collectClassNames()

	var buf bytes.Buffer
	buf.WriteString(`# Code generated by cmd/clientgen from api/openapi.yaml; DO NOT EDIT.
#
# The generated surface (models, query parameter dataclasses, per-operation
# methods, SPEC_ROUTES and SPEC_VERSION) is verified against api/openapi.yaml
# by pkg/client/python_drift_test.go. Regenerate with ` + "`make client`" + ` after
# changing the spec.

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from decimal import Decimal
from typing import Final, TypeAlias
import urllib.parse

JSONScalar: TypeAlias = str | int | Decimal | bool | None
JSONValue: TypeAlias = JSONScalar | list["JSONValue"] | dict[str, "JSONValue"]
JSONObject: TypeAlias = dict[str, JSONValue]

SPEC_VERSION: Final[str] = ` + strconv.Quote(spec.Info.Version) + "\n\n")

	pg.emitPySpecRoutes(&buf, spec)
	pg.emitPyHelpers(&buf)
	pg.emitPySchemas(&buf)
	pg.emitPyOperations(&buf, ops)

	return buf.Bytes()
}

func (pg *pyGenerator) collectClassNames() {
	for _, name := range sortedKeys(pg.schemas) {
		s := pg.schemas[name]
		if pg.isClassSchema(s) {
			pg.classNames[name] = true
			pg.discoverInlineSchemas(name, s, 0)
		}
	}
	for _, name := range sortedKeys(pg.synthNames) {
		s := pg.synthNames[name]
		if pg.isClassSchema(s) {
			pg.classNames[name] = true
			pg.discoverInlineSchemas(name, s, 0)
		}
	}
}

func (pg *pyGenerator) isClassSchema(s *rawSchema) bool {
	if s == nil || s.Ref != "" {
		return false
	}
	if s.Type == "object" && len(s.Properties) > 0 {
		return true
	}
	if len(s.AllOf) > 0 {
		props, _ := pg.flattenAllOf(s, 0)
		return len(props) > 0
	}
	return false
}

func (pg *pyGenerator) discoverInlineSchemas(owner string, s *rawSchema, depth int) {
	if s == nil || depth > 8 {
		return
	}
	props, _ := pg.effectiveProperties(s, depth)
	for _, propName := range sortedKeys(props) {
		prop := props[propName]
		if prop == nil {
			continue
		}
		if (prop.Type == "object" || hasVariantType(prop, "object")) && len(prop.Properties) > 0 {
			inlineName := owner + goFieldName(propName)
			pg.inlineSchemas[inlineName] = prop
			pg.classNames[inlineName] = true
			pg.discoverInlineSchemas(inlineName, prop, depth+1)
		} else if prop.Type == "array" && prop.Items != nil && prop.Items.Type == "object" && len(prop.Items.Properties) > 0 {
			inlineName := owner + goFieldName(propName) + "Item"
			pg.inlineSchemas[inlineName] = prop.Items
			pg.classNames[inlineName] = true
			pg.discoverInlineSchemas(inlineName, prop.Items, depth+1)
		}
	}
}

func (pg *pyGenerator) effectiveProperties(s *rawSchema, depth int) (map[string]*rawSchema, []string) {
	if len(s.AllOf) > 0 {
		return pg.flattenAllOf(s, depth)
	}
	return s.Properties, s.Required
}

func (pg *pyGenerator) flattenAllOf(s *rawSchema, depth int) (map[string]*rawSchema, []string) {
	if depth > 8 {
		return nil, nil
	}
	props := map[string]*rawSchema{}
	var req []string
	for _, member := range s.AllOf {
		if member == nil {
			continue
		}
		if member.Ref != "" {
			refName := schemaBase(member.Ref)
			if target, ok := pg.schemas[refName]; ok {
				subProps, subReq := pg.effectiveProperties(target, depth+1)
				for k, v := range subProps {
					props[k] = v
				}
				req = append(req, subReq...)
			}
			continue
		}
		for k, v := range member.Properties {
			props[k] = v
		}
		req = append(req, member.Required...)
	}
	for k, v := range s.Properties {
		props[k] = v
	}
	req = append(req, s.Required...)
	return props, req
}

func (pg *pyGenerator) emitPySpecRoutes(buf *bytes.Buffer, spec *rawSpec) {
	buf.WriteString("SPEC_ROUTES: Final[tuple[tuple[str, str], ...]] = (\n")
	for _, path := range sortedKeys(spec.Paths) {
		for _, method := range sortedKeys(spec.Paths[path]) {
			fmt.Fprintf(buf, "    (%q, %q),\n", strings.ToUpper(method), path)
		}
	}
	buf.WriteString(")\n\n")
}

func (pg *pyGenerator) emitPyHelpers(buf *bytes.Buffer) {
	buf.WriteString(`def _as_str(val: object, default: str = "") -> str:
    return val if isinstance(val, str) else default


def _as_opt_str(val: object) -> str | None:
    return val if isinstance(val, str) else None


def _as_int(val: object, default: int = 0) -> int:
    if isinstance(val, bool):
        return default
    if isinstance(val, int):
        return val
    return default


def _as_opt_int(val: object) -> int | None:
    if isinstance(val, bool):
        return None
    if isinstance(val, int):
        return val
    return None


def _as_bool(val: object, default: bool = False) -> bool:
    return val if isinstance(val, bool) else default


def _as_decimal(val: object, default: Decimal = Decimal(0)) -> Decimal:
    if isinstance(val, Decimal):
        return val
    if isinstance(val, int) and not isinstance(val, bool):
        return Decimal(val)
    if isinstance(val, float):
        return Decimal(str(val))
    if isinstance(val, str):
        try:
            return Decimal(val)
        except Exception:
            return default
    return default


def _as_opt_decimal(val: object) -> Decimal | None:
    if val is None or isinstance(val, bool):
        return None
    if isinstance(val, Decimal):
        return val
    if isinstance(val, int):
        return Decimal(val)
    if isinstance(val, float):
        return Decimal(str(val))
    if isinstance(val, str):
        try:
            return Decimal(val)
        except Exception:
            return None
    return None


def _as_json_val(val: object) -> JSONValue:
    if val is None or isinstance(val, (str, int, Decimal, bool)):
        return val
    if isinstance(val, float):
        return Decimal(str(val))
    if isinstance(val, list):
        return [_as_json_val(item) for item in val]
    if isinstance(val, dict):
        return {str(k): _as_json_val(v) for k, v in val.items()}
    return str(val)


def _as_json_obj(val: object) -> JSONObject:
    if isinstance(val, dict):
        return {str(k): _as_json_val(v) for k, v in val.items()}
    return {}


def _as_str_list(val: object) -> list[str]:
    if isinstance(val, list):
        return [item for item in val if isinstance(item, str)]
    return []


def _as_json_list(val: object) -> list[JSONValue]:
    if isinstance(val, list):
        return [_as_json_val(item) for item in val]
    return []


def _escape_path(template: str, *args: str) -> str:
    out = template
    for arg in args:
        start = out.find("{")
        end = out.find("}")
        if start < 0 or end < start:
            break
        out = out[:start] + urllib.parse.quote(arg, safe="") + out[end + 1 :]
    return out


`)
}

func (pg *pyGenerator) emitPySchemas(buf *bytes.Buffer) {
	// 1. Emit inline nested object dataclasses first so parent classes can
	// reference them in default_factory or from_dict.
	for _, name := range sortedKeys(pg.inlineSchemas) {
		pg.emitPyDataclass(buf, name, pg.inlineSchemas[name])
	}

	// 2. Emit component and synthesized dataclasses.
	var aliases []struct {
		name   string
		schema *rawSchema
	}
	for _, name := range sortedKeys(pg.schemas) {
		s := pg.schemas[name]
		if pg.isClassSchema(s) {
			pg.emitPyDataclass(buf, name, s)
		} else {
			aliases = append(aliases, struct {
				name   string
				schema *rawSchema
			}{name: name, schema: s})
		}
	}
	for _, name := range sortedKeys(pg.synthNames) {
		s := pg.synthNames[name]
		if pg.isClassSchema(s) {
			pg.emitPyDataclass(buf, name, s)
		} else {
			aliases = append(aliases, struct {
				name   string
				schema *rawSchema
			}{name: name, schema: s})
		}
	}

	// 3. Emit type aliases after all classes are defined.
	for _, a := range aliases {
		pg.emitPyAlias(buf, a.name, a.schema)
	}
}

func (pg *pyGenerator) emitPyDataclass(buf *bytes.Buffer, name string, s *rawSchema) {
	doc := cleanDoc(s.Description, "API schema used by the SoroTrail client.")
	fields := pg.buildPyFields(name, s)

	buf.WriteString("@dataclass(slots=True)\n")
	fmt.Fprintf(buf, "class %s:\n", name)
	fmt.Fprintf(buf, "    %s\n\n", pyDocstring(doc))

	for _, f := range fields {
		if f.Description != "" {
			fmt.Fprintf(buf, "    # %s\n", f.Description)
		}
		if f.DeprecatedNotice != "" {
			fmt.Fprintf(buf, "    # Deprecated: %s\n", f.DeprecatedNotice)
		}
		fmt.Fprintf(buf, "    %s: %s = %s\n", f.PyName, f.PyType, f.DefaultExpr)
	}
	buf.WriteString("\n    @classmethod\n")
	fmt.Fprintf(buf, "    def from_dict(cls, data: Mapping[str, JSONValue]) -> %s:\n", name)
	fmt.Fprintf(buf, "        return cls(\n")
	for _, f := range fields {
		fmt.Fprintf(buf, "            %s=%s,\n", f.PyName, f.FromDict)
	}
	buf.WriteString("        )\n\n")

	buf.WriteString("    def to_dict(self) -> JSONObject:\n")
	buf.WriteString("        out: JSONObject = {}\n")
	for _, f := range fields {
		buf.WriteString(f.ToDictExpr)
	}
	buf.WriteString("        return out\n\n\n")
}

func (pg *pyGenerator) emitPyAlias(buf *bytes.Buffer, name string, s *rawSchema) {
	doc := cleanDoc(s.Description, "API schema alias used by the SoroTrail client.")
	fmt.Fprintf(buf, "# %s: %s\n", name, doc)
	switch {
	case s.Ref != "":
		fmt.Fprintf(buf, "%s: TypeAlias = %s\n\n", name, schemaBase(s.Ref))
	case s.OneOf != nil:
		if ref := firstOneOfRef(s); ref != "" {
			fmt.Fprintf(buf, "%s: TypeAlias = %s\n\n", name, ref)
		} else {
			fmt.Fprintf(buf, "%s: TypeAlias = JSONObject\n\n", name)
		}
	case s.Type == "array":
		elem := "JSONValue"
		if s.Items != nil && s.Items.Ref != "" {
			elem = schemaBase(s.Items.Ref)
		} else if s.Items != nil && s.Items.Type == "string" {
			elem = "str"
		}
		fmt.Fprintf(buf, "%s: TypeAlias = list[%s]\n\n", name, elem)
	case s.Type == "string":
		fmt.Fprintf(buf, "%s: TypeAlias = str\n\n", name)
	case s.Type == "integer":
		fmt.Fprintf(buf, "%s: TypeAlias = int\n\n", name)
	case s.Type == "boolean":
		fmt.Fprintf(buf, "%s: TypeAlias = bool\n\n", name)
	default:
		fmt.Fprintf(buf, "%s: TypeAlias = JSONObject\n\n", name)
	}
}

func (pg *pyGenerator) buildPyFields(owner string, s *rawSchema) []pyField {
	props, req := pg.effectiveProperties(s, 0)
	var out []pyField
	for _, wireName := range sortedKeys(props) {
		prop := props[wireName]
		if prop == nil {
			continue
		}
		pyName := toSnakeCase(wireName)
		optional := !contains(req, wireName)
		nullable := prop.Nullable || hasVariantType(prop, "null")
		desc := cleanDoc(prop.Description, "")

		f := pg.classifyPyField(owner, wireName, pyName, prop, optional, nullable)
		f.Description = desc
		f.DeprecatedNotice = deprecationNotice(prop.Deprecated, prop.DeprecationNotice, prop.SunsetDate, prop.DeprecationReplacement, fmt.Sprintf("%s is deprecated.", pyName))
		out = append(out, f)
	}
	return out
}

func (pg *pyGenerator) classifyPyField(owner, wireName, pyName string, prop *rawSchema, optional, nullable bool) pyField {
	f := pyField{
		WireName: wireName,
		PyName:   pyName,
		Optional: optional,
	}
	wireLit := strconv.Quote(wireName)

	// Case 1: $ref or single-element allOf $ref.
	refName := ""
	if prop.Ref != "" {
		refName = schemaBase(prop.Ref)
	} else if len(prop.AllOf) == 1 && prop.AllOf[0].Ref != "" {
		refName = schemaBase(prop.AllOf[0].Ref)
	}
	if refName != "" && pg.classNames[refName] {
		if optional || nullable {
			f.PyType = refName + " | None"
			f.DefaultExpr = "None"
			f.FromDict = fmt.Sprintf("%s.from_dict(_as_json_obj(data[%s])) if isinstance(data.get(%s), dict) else None", refName, wireLit, wireLit)
			f.ToDictExpr = fmt.Sprintf("        if self.%s is not None:\n            out[%s] = self.%s.to_dict()\n", pyName, wireLit, pyName)
		} else {
			f.PyType = refName
			f.DefaultExpr = fmt.Sprintf("field(default_factory=lambda: %s())", refName)
			f.FromDict = fmt.Sprintf("%s.from_dict(_as_json_obj(data.get(%s)))", refName, wireLit)
			f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s.to_dict()\n", wireLit, pyName)
		}
		return f
	}

	// Case 2: Inline object with properties.
	if (prop.Type == "object" || hasVariantType(prop, "object")) && len(prop.Properties) > 0 {
		inlineName := owner + goFieldName(wireName)
		f.PyType = inlineName + " | None"
		f.DefaultExpr = "None"
		f.FromDict = fmt.Sprintf("%s.from_dict(_as_json_obj(data[%s])) if isinstance(data.get(%s), dict) else None", inlineName, wireLit, wireLit)
		f.ToDictExpr = fmt.Sprintf("        if self.%s is not None:\n            out[%s] = self.%s.to_dict()\n", pyName, wireLit, pyName)
		return f
	}

	// Case 3: Array (or nullable array like EventWithXDR.topics_xdr).
	if prop.Type == "array" || hasVariantType(prop, "array") {
		f.DefaultExpr = "field(default_factory=list)"
		elemClass := ""
		if prop.Items != nil {
			if prop.Items.Ref != "" {
				cand := schemaBase(prop.Items.Ref)
				if pg.classNames[cand] {
					elemClass = cand
				}
			} else if prop.Items.OneOf != nil {
				cand := firstOneOfRef(prop.Items)
				if pg.classNames[cand] {
					elemClass = cand
				}
			} else if prop.Items.Type == "object" && len(prop.Items.Properties) > 0 {
				elemClass = owner + goFieldName(wireName) + "Item"
			}
		}
		if elemClass != "" {
			f.PyType = fmt.Sprintf("list[%s]", elemClass)
			f.FromDict = fmt.Sprintf("[%s.from_dict(_as_json_obj(item)) for item in _as_json_list(data.get(%s)) if isinstance(item, dict)]", elemClass, wireLit)
			if optional {
				f.ToDictExpr = fmt.Sprintf("        if self.%s:\n            out[%s] = [item.to_dict() for item in self.%s]\n", pyName, wireLit, pyName)
			} else {
				f.ToDictExpr = fmt.Sprintf("        out[%s] = [item.to_dict() for item in self.%s]\n", wireLit, pyName)
			}
			return f
		}
		if prop.Items != nil && prop.Items.Type == "string" {
			f.PyType = "list[str]"
			f.FromDict = fmt.Sprintf("_as_str_list(data.get(%s))", wireLit)
			if optional {
				f.ToDictExpr = fmt.Sprintf("        if self.%s:\n            out[%s] = list(self.%s)\n", pyName, wireLit, pyName)
			} else {
				f.ToDictExpr = fmt.Sprintf("        out[%s] = list(self.%s)\n", wireLit, pyName)
			}
			return f
		}
		f.PyType = "list[JSONValue]"
		f.FromDict = fmt.Sprintf("_as_json_list(data.get(%s))", wireLit)
		if optional {
			f.ToDictExpr = fmt.Sprintf("        if self.%s:\n            out[%s] = list(self.%s)\n", pyName, wireLit, pyName)
		} else {
			f.ToDictExpr = fmt.Sprintf("        out[%s] = list(self.%s)\n", wireLit, pyName)
		}
		return f
	}

	// Case 4: Scalars.
	switch {
	case prop.Type == "string" || hasVariantType(prop, "string"):
		if nullable {
			f.PyType = "str | None"
			f.DefaultExpr = "None"
			f.FromDict = fmt.Sprintf("_as_opt_str(data.get(%s))", wireLit)
			f.ToDictExpr = fmt.Sprintf("        if self.%s is not None:\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
		} else {
			f.PyType = "str"
			f.DefaultExpr = `""`
			f.FromDict = fmt.Sprintf("_as_str(data.get(%s))", wireLit)
			if optional {
				f.ToDictExpr = fmt.Sprintf("        if self.%s != \"\":\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
			} else {
				f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s\n", wireLit, pyName)
			}
		}
		return f

	case prop.Type == "integer" || hasVariantType(prop, "integer"):
		if nullable {
			f.PyType = "int | None"
			f.DefaultExpr = "None"
			f.FromDict = fmt.Sprintf("_as_opt_int(data.get(%s))", wireLit)
			if optional {
				f.ToDictExpr = fmt.Sprintf("        if self.%s is not None:\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
			} else {
				f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s\n", wireLit, pyName)
			}
		} else {
			f.PyType = "int"
			f.DefaultExpr = "0"
			f.FromDict = fmt.Sprintf("_as_int(data.get(%s))", wireLit)
			if optional {
				f.ToDictExpr = fmt.Sprintf("        if self.%s != 0:\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
			} else {
				f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s\n", wireLit, pyName)
			}
		}
		return f

	case prop.Type == "number" || hasVariantType(prop, "number"):
		if nullable {
			f.PyType = "Decimal | None"
			f.DefaultExpr = "None"
			f.FromDict = fmt.Sprintf("_as_opt_decimal(data.get(%s))", wireLit)
			f.ToDictExpr = fmt.Sprintf("        if self.%s is not None:\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
		} else {
			f.PyType = "Decimal"
			f.DefaultExpr = "Decimal(0)"
			f.FromDict = fmt.Sprintf("_as_decimal(data.get(%s))", wireLit)
			if optional {
				f.ToDictExpr = fmt.Sprintf("        if self.%s != Decimal(0):\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
			} else {
				f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s\n", wireLit, pyName)
			}
		}
		return f

	case prop.Type == "boolean" || hasVariantType(prop, "boolean"):
		f.PyType = "bool"
		f.DefaultExpr = "False"
		f.FromDict = fmt.Sprintf("_as_bool(data.get(%s))", wireLit)
		if optional {
			f.ToDictExpr = fmt.Sprintf("        if self.%s:\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
		} else {
			f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s\n", wireLit, pyName)
		}
		return f

	case prop.Type == "object":
		f.PyType = "JSONObject"
		f.DefaultExpr = "field(default_factory=dict)"
		f.FromDict = fmt.Sprintf("_as_json_obj(data.get(%s))", wireLit)
		if optional {
			f.ToDictExpr = fmt.Sprintf("        if self.%s:\n            out[%s] = dict(self.%s)\n", pyName, wireLit, pyName)
		} else {
			f.ToDictExpr = fmt.Sprintf("        out[%s] = dict(self.%s)\n", wireLit, pyName)
		}
		return f

	default:
		f.PyType = "JSONValue"
		f.DefaultExpr = "None"
		f.FromDict = fmt.Sprintf("_as_json_val(data.get(%s))", wireLit)
		if optional {
			f.ToDictExpr = fmt.Sprintf("        if self.%s is not None:\n            out[%s] = self.%s\n", pyName, wireLit, pyName)
		} else {
			f.ToDictExpr = fmt.Sprintf("        out[%s] = self.%s\n", wireLit, pyName)
		}
		return f
	}
}

func (pg *pyGenerator) emitPyOperations(buf *bytes.Buffer, ops []genOperation) {
	// First emit query parameter dataclasses.
	for _, op := range ops {
		if len(op.Query) == 0 {
			continue
		}
		pg.emitPyParamsClass(buf, op)
	}

	// Emit _GeneratedClientBase with abstract transport hooks and all 50 typed
	// operation methods.
	buf.WriteString(`class _GeneratedClientBase:
    """Generated per-operation methods for the SoroTrail HTTP API."""

    def _request_json(
        self,
        method: str,
        path: str,
        query: Mapping[str, str] | None = None,
        body: JSONObject | None = None,
    ) -> JSONValue:
        raise NotImplementedError

    def _request_bytes(
        self,
        method: str,
        path: str,
        query: Mapping[str, str] | None = None,
        body: JSONObject | None = None,
    ) -> bytes:
        raise NotImplementedError

    def _request_no_content(
        self,
        method: str,
        path: str,
        query: Mapping[str, str] | None = None,
        body: JSONObject | None = None,
    ) -> None:
        raise NotImplementedError

`)

	for _, op := range ops {
		pg.emitPyOperationMethod(buf, op)
	}
}

func (pg *pyGenerator) emitPyParamsClass(buf *bytes.Buffer, op genOperation) {
	className := op.GoName + "Params"
	buf.WriteString("@dataclass(slots=True)\n")
	fmt.Fprintf(buf, "class %s:\n", className)
	fmt.Fprintf(buf, "    %s\n\n", pyDocstring("Query parameters for "+toSnakeCase(op.GoName)+"."))
	for _, p := range op.Query {
		pyName := toSnakeCase(p.Name)
		switch p.Type {
		case "int64":
			fmt.Fprintf(buf, "    %s: int = 0\n", pyName)
		case "bool":
			fmt.Fprintf(buf, "    %s: bool = False\n", pyName)
		default:
			fmt.Fprintf(buf, "    %s: str = \"\"\n", pyName)
		}
	}
	buf.WriteString("\n    def to_query(self) -> dict[str, str]:\n")
	buf.WriteString("        q: dict[str, str] = {}\n")
	for _, p := range op.Query {
		pyName := toSnakeCase(p.Name)
		wireLit := strconv.Quote(p.Name)
		switch p.Type {
		case "int64":
			fmt.Fprintf(buf, "        if self.%s != 0:\n            q[%s] = str(self.%s)\n", pyName, wireLit, pyName)
		case "bool":
			fmt.Fprintf(buf, "        if self.%s:\n            q[%s] = \"true\"\n", pyName, wireLit)
		default:
			fmt.Fprintf(buf, "        if self.%s != \"\":\n            q[%s] = self.%s\n", pyName, wireLit, pyName)
		}
	}
	buf.WriteString("        return q\n\n\n")
}

func (pg *pyGenerator) emitPyOperationMethod(buf *bytes.Buffer, op genOperation) {
	methodName := toSnakeCase(op.GoName)
	args := []string{"self"}
	for _, a := range op.PathArgs {
		pyArg := toSnakeCase(a.Name)
		pyType := "str"
		switch a.Type {
		case "int64":
			pyType = "int"
		case "bool":
			pyType = "bool"
		}
		args = append(args, fmt.Sprintf("%s: %s", pyArg, pyType))
	}
	if op.HasBody {
		args = append(args, fmt.Sprintf("body: %s", op.BodyType))
	}
	if len(op.Query) > 0 {
		args = append(args, fmt.Sprintf("params: %sParams | None = None", op.GoName))
	}

	retType := "None"
	targetClass := ""
	isSlice := false
	isRaw := false
	isVoid := false

	switch {
	case op.RespRef != "":
		retType = op.RespRef
		targetClass = pg.resolveTargetClass(op.RespRef)
	case op.RespSynth != "":
		retType = op.RespSynth
		targetClass = pg.resolveTargetClass(op.RespSynth)
	case op.RespArray != "":
		retType = fmt.Sprintf("list[%s]", op.RespArray)
		targetClass = pg.resolveTargetClass(op.RespArray)
		isSlice = true
	case op.RespRaw:
		retType = "bytes"
		isRaw = true
	default:
		isVoid = true
	}

	doc := cleanDoc(op.Summary, op.GoName)
	docLine := fmt.Sprintf("%s (%s %s).", strings.TrimSuffix(doc, "."), op.Method, op.Path)
	if op.DeprecatedNotice != "" {
		docLine += " Deprecated: " + op.DeprecatedNotice
	}
	fmt.Fprintf(buf, "    def %s(%s) -> %s:\n", methodName, strings.Join(args, ", "), retType)
	fmt.Fprintf(buf, "        %s\n", pyDocstring(docLine))

	// Path construction.
	if len(op.PathArgs) == 0 {
		fmt.Fprintf(buf, "        path = %q\n", op.Path)
	} else {
		var escArgs []string
		for _, a := range op.PathArgs {
			pyArg := toSnakeCase(a.Name)
			if a.Type == "int64" || a.Type == "bool" {
				escArgs = append(escArgs, fmt.Sprintf("str(%s)", pyArg))
			} else {
				escArgs = append(escArgs, pyArg)
			}
		}
		fmt.Fprintf(buf, "        path = _escape_path(%q, %s)\n", op.Path, strings.Join(escArgs, ", "))
	}

	queryExpr := "None"
	if len(op.Query) > 0 {
		buf.WriteString("        query = params.to_query() if params is not None else None\n")
		queryExpr = "query"
	}

	bodyExpr := "None"
	if op.HasBody {
		if pg.classNames[op.BodyType] {
			buf.WriteString("        payload = body.to_dict()\n")
		} else {
			buf.WriteString("        payload = dict(body)\n")
		}
		bodyExpr = "payload"
	}

	switch {
	case isVoid:
		fmt.Fprintf(buf, "        self._request_no_content(%q, path, %s, %s)\n\n", op.Method, queryExpr, bodyExpr)
	case isRaw:
		fmt.Fprintf(buf, "        return self._request_bytes(%q, path, %s, %s)\n\n", op.Method, queryExpr, bodyExpr)
	case isSlice:
		fmt.Fprintf(buf, "        raw = self._request_json(%q, path, %s, %s)\n", op.Method, queryExpr, bodyExpr)
		fmt.Fprintf(buf, "        if not isinstance(raw, list):\n            return []\n")
		fmt.Fprintf(buf, "        return [%s.from_dict(_as_json_obj(item)) for item in raw if isinstance(item, dict)]\n\n", targetClass)
	case targetClass != "":
		fmt.Fprintf(buf, "        raw = self._request_json(%q, path, %s, %s)\n", op.Method, queryExpr, bodyExpr)
		if targetClass == "DeliveryEnvelopeResponse" {
			buf.WriteString("        if isinstance(raw, list):\n")
			buf.WriteString("            return DeliveryEnvelopeResponse.from_dict({\"data\": _as_json_list(raw)})\n")
		}
		fmt.Fprintf(buf, "        return %s.from_dict(_as_json_obj(raw))\n\n", targetClass)
	default:
		fmt.Fprintf(buf, "        raw = self._request_json(%q, path, %s, %s)\n", op.Method, queryExpr, bodyExpr)
		buf.WriteString("        return _as_json_obj(raw)\n\n")
	}
}

func (pg *pyGenerator) resolveTargetClass(name string) string {
	if pg.classNames[name] {
		return name
	}
	if s, ok := pg.schemas[name]; ok {
		if s.Ref != "" {
			ref := schemaBase(s.Ref)
			if pg.classNames[ref] {
				return ref
			}
		}
		if s.OneOf != nil {
			ref := firstOneOfRef(s)
			if pg.classNames[ref] {
				return ref
			}
		}
	}
	if s, ok := pg.synthNames[name]; ok {
		if s.Ref != "" {
			ref := schemaBase(s.Ref)
			if pg.classNames[ref] {
				return ref
			}
		}
		if s.OneOf != nil {
			ref := firstOneOfRef(s)
			if pg.classNames[ref] {
				return ref
			}
		}
	}
	return ""
}

func hasVariantType(s *rawSchema, typ string) bool {
	if s == nil {
		return false
	}
	for _, m := range s.OneOf {
		if m != nil && m.Type == typ {
			return true
		}
	}
	return false
}

func cleanDoc(s, fallback string) string {
	doc := strings.TrimSpace(s)
	if doc == "" {
		doc = fallback
	}
	return strings.Join(strings.Fields(doc), " ")
}

func pyDocstring(doc string) string {
	escaped := strings.ReplaceAll(doc, `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `"""`, `\"\"\"`)
	return `"""` + escaped + `"""`
}

// toSnakeCase converts camelCase, PascalCase, or kebab-case identifiers into
// idiomatic Python snake_case while keeping acronyms together (e.g.
// "createAPIKey" -> "create_api_key", "exportEventsCSV" -> "export_events_csv").
func toSnakeCase(s string) string {
	if s == "" {
		return s
	}
	runes := []rune(s)
	var sb strings.Builder
	for i, r := range runes {
		if r == '_' || r == '-' || r == ' ' {
			if sb.Len() > 0 && !strings.HasSuffix(sb.String(), "_") {
				sb.WriteRune('_')
			}
			continue
		}
		if unicode.IsUpper(r) {
			if i > 0 {
				prev := runes[i-1]
				prevSep := prev == '_' || prev == '-' || prev == ' '
				if !prevSep {
					nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
					if unicode.IsLower(prev) || unicode.IsDigit(prev) || (unicode.IsUpper(prev) && nextLower) {
						sb.WriteRune('_')
					}
				}
			}
			sb.WriteRune(unicode.ToLower(r))
		} else {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}
